const SKIP_SELECTOR = 'iframe, table, script, style, textarea, input, [contenteditable="true"], .office-word-content, .office-sheet-data, .user-document-content';

function translateText(value: string): string {
  const trimmed = value.trim();
  if (!trimmed) return value;
  const exact = EXACT[trimmed];
  if (exact) return value.replace(trimmed, exact);
  let translated = value;
  for (const [from, to] of PHRASES) translated = translated.split(from).join(to);
  return translated;
}

function translateNode(node: Node, root: HTMLElement) {
  if (node.nodeType === Node.TEXT_NODE) {
    const parent = node.parentElement;
    if (!parent || parent.closest(SKIP_SELECTOR)) return;
    const original = node.nodeValue || '';
    const translated = translateText(original);
    if (translated !== original) node.nodeValue = translated;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  const element = node as HTMLElement;
  if (element.closest(SKIP_SELECTOR)) return;
  for (const attr of ['title', 'placeholder', 'aria-label']) {
    const value = element.getAttribute(attr);
    if (value) {
      const translated = translateText(value);
      if (translated !== value) element.setAttribute(attr, translated);
    }
  }
  if (element !== root) {
    for (const child of Array.from(element.childNodes)) translateNode(child, root);
  }
}

export function installUkrainianLocale(root: HTMLElement): () => void {
  translateNode(root, root);
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'characterData') translateNode(record.target, root);
      for (const node of Array.from(record.addedNodes)) translateNode(node, root);
    }
  });
  observer.observe(root, { subtree: true, childList: true, characterData: true });
  return () => observer.disconnect();
}
